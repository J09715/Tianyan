param(
    [Parameter(Mandatory = $true)]
    [string]$NdkRoot
)

$ErrorActionPreference = 'Stop'
$taskRepoRoot = Split-Path -Parent $PSScriptRoot
$taskToolchain = Join-Path $NdkRoot 'toolchains/llvm/prebuilt/windows-x86_64/bin'
$taskCompiler = Join-Path $taskToolchain 'clang.exe'
$taskReadelf = Join-Path $taskToolchain 'llvm-readelf.exe'
if (!(Test-Path -LiteralPath $taskCompiler) -or !(Test-Path -LiteralPath $taskReadelf)) {
    throw 'Expected a Windows Android NDK toolchain in -NdkRoot.'
}
$taskOutputDir = Join-Path $taskRepoRoot 'app/build/pty-native'
New-Item -ItemType Directory -Force -Path $taskOutputDir | Out-Null
$taskOutput = Join-Path $taskOutputDir 'libpty_native.so'
$taskSource = Join-Path $taskRepoRoot 'app/src/main/cpp/pty_native.c'
& $taskCompiler --target=aarch64-linux-android29 -shared -fPIC -O2 -Wall `
    -Werror=implicit-function-declaration '-Wl,-z,max-page-size=16384' $taskSource -o $taskOutput
if ($LASTEXITCODE -ne 0) { throw "PTY compilation failed: $LASTEXITCODE" }
$taskSymbols = & $taskReadelf --dyn-syms --needed-libs $taskOutput
if ($LASTEXITCODE -ne 0) { throw "PTY symbol inspection failed: $LASTEXITCODE" }
if (!($taskSymbols -match 'Java_top_tianyan_app_runtime_pty_NativePty_pollExit') -or
    ($taskSymbols -match 'libc\.so\.6')) {
    throw 'PTY library has an incompatible JNI interface or libc dependency.'
}
$taskDestination = Join-Path $taskRepoRoot 'app/src/main/jniLibs/arm64-v8a/libpty_native.so'
Copy-Item -LiteralPath $taskOutput -Destination $taskDestination -Force
$taskSourceText = [IO.File]::ReadAllText($taskSource).Replace("`r`n", "`n")
$taskHasher = [Security.Cryptography.SHA256]::Create()
try {
    $taskSourceHash = [BitConverter]::ToString($taskHasher.ComputeHash(
        [Text.Encoding]::UTF8.GetBytes($taskSourceText))).Replace('-', '').ToLowerInvariant()
} finally { $taskHasher.Dispose() }
$taskBinaryHash = (Get-FileHash -LiteralPath $taskDestination -Algorithm SHA256).Hash.ToLowerInvariant()
$taskManifest = Join-Path $taskRepoRoot 'app/src/main/cpp/pty-native.properties'
[IO.File]::WriteAllLines($taskManifest, @(
    '# Generated by tools/build-pty-native.ps1; commit with the source and binary.'
    'format.version=1'
    'abi=arm64-v8a'
    'api.level=29'
    "source.sha256=$taskSourceHash"
    "binary.sha256=$taskBinaryHash"
), [Text.UTF8Encoding]::new($false))
$taskSymbols
